-- Courtside Kits — Supabase schema + seed data
-- Run this whole file once in Supabase Dashboard → SQL Editor → New query → Run.

create table if not exists public.jerseys (
  id              bigint generated by default as identity primary key,
  player_name     text        not null,
  team            text        not null,
  number          text        not null,
  edition         text        not null default 'Icon'
                  check (edition in ('Icon', 'Association', 'Statement', 'City', 'Classic')),
  price           numeric(10, 2) not null check (price >= 0),
  stock           integer     not null default 0 check (stock >= 0),
  primary_color   text        not null default '#1D428A',
  secondary_color text        not null default '#FFFFFF',
  created_at      timestamptz not null default now()
);

-- Speeds up the price-range filter + ordering used by pagination.
create index if not exists jerseys_price_idx on public.jerseys (price, id);

-- Row Level Security: this is a class demo, so anyone with the anon key can
-- read and manage products. Tighten these policies for a real store.
alter table public.jerseys enable row level security;

drop policy if exists "Public read jerseys"   on public.jerseys;
drop policy if exists "Public insert jerseys" on public.jerseys;
drop policy if exists "Public update jerseys" on public.jerseys;
drop policy if exists "Public delete jerseys" on public.jerseys;

create policy "Public read jerseys"   on public.jerseys for select using (true);
create policy "Public insert jerseys" on public.jerseys for insert with check (true);
create policy "Public update jerseys" on public.jerseys for update using (true) with check (true);
create policy "Public delete jerseys" on public.jerseys for delete using (true);

